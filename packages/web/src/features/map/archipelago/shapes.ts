/**
 * 32-bit FNV-1a hash to deterministically map page identifiers to coastlines.
 */
function fnv1aHash(str: string): number {
  let hash = 2166136261
  for (let i = 0; i < str.length; i++) {
    hash ^= str.charCodeAt(i)
    hash = Math.imul(hash, 16777619)
  }
  hash ^= hash >>> 16
  hash = Math.imul(hash, 0x7feb352d)
  hash ^= hash >>> 15
  hash = Math.imul(hash, 0x846ca68b)
  return (hash ^ (hash >>> 16)) >>> 0
}

export function getIslandShape(pageId: string): string {
  const index = fnv1aHash(`${pageId}:coastline`) % ISLAND_SHAPES.length
  return ISLAND_SHAPES[index] ?? ISLAND_SHAPES[0]
}
